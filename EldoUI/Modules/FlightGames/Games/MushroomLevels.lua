local function Rect(x, y, w, h, kind)
	return { x = x, y = y, w = w, h = h, kind = kind }
end

for _, level in ipairs(levels) do
	level.width = level.width * TILE
	level.start = { x = 48, y = GROUND }
	level.terrain = {}
	for _, span in ipairs(level.ground) do
		local top = span[3] or GROUND
		level.terrain[#level.terrain + 1] = Rect(span[1] * TILE, top, span[2] * TILE, 360 - top, "ground")
	end
	for _, span in ipairs(level.ledges) do
		level.terrain[#level.terrain + 1] = Rect(span[1] * TILE, span[3], span[2] * TILE, 14, "ledge")
	end
	level.ground, level.ledges = nil, nil
	for index, block in ipairs(level.blocks) do level.blocks[index] = Rect(block[1] * TILE, block[2], 29, 26, block[3]) end
	local coins = {}
	for _, line in ipairs(level.coins) do
		for index = 0, line[3] - 1 do coins[#coins + 1] = Rect(line[1] * TILE + index * 24, line[2], 15, 15, "coin") end
	end
	level.coins = coins
	for index, row in ipairs(level.enemies) do
		local body = Rect(row[1] * TILE, (row[4] or GROUND) - 20, 24, 20, row[5] or "crawler")
		body.left, body.right = row[2] * TILE, (row[3] + 1) * TILE - body.w
		level.enemies[index] = body
	end
	for index, row in ipairs(level.hazards) do level.hazards[index] = Rect(row[1] * TILE, (row[3] or GROUND) - 13, row[2] * TILE, 13, "thorn") end
	for index, row in ipairs(level.checkpoints) do level.checkpoints[index] = { x = row[1] * TILE, y = row[2] or GROUND } end
	level.exit = Rect(level.exit[1] * TILE, (level.exit[2] or GROUND) - 58, 33, 58, "exit")
end

M.MushroomLevels = levels
