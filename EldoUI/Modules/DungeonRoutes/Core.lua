---------------------------------------------------------------------------
-- Editing your own routes (the editor, Editor.lua). Every change keeps an
-- undo step first. Shipped routes are never changed: copy one first.
---------------------------------------------------------------------------
local undo = {}            -- route id -> { snapshot, ... }

local function Snapshot(route)
	return { pulls = CopyTable(route.pulls or {}), n = route.n and CopyTable(route.n), a = route.a and CopyTable(route.a), d = route.d and CopyTable(route.d) }
end

-- Runs fn(route) on one of your routes with an undo step; fn returns true
-- (and an optional result) when it changed something, else the step goes.
function M:EditRoute(id, fn)
	local route = self:GetRoute(id)
	if not route or route.shipped then return false end
	local steps = undo[route.id] or {}
	undo[route.id] = steps
	steps[#steps + 1] = Snapshot(route)
	local ok, changed, result = pcall(fn, route)
	if not ok then
		table.remove(steps)
		geterrorhandler()(changed)
		return false
	end
	if not changed then
		table.remove(steps)
		return false
	end
	while #steps > MAX_UNDO do table.remove(steps, 1) end
	self:Changed("route")
	return true, result
end

function M:CanUndo(id)
	local steps = undo[tonumber(id) or -1]
	return steps ~= nil and #steps > 0
end

function M:Undo(id)
	local route = self:GetRoute(id)
	local steps = route and undo[route.id]
	local last = steps and table.remove(steps)
	if not last then return false end
	route.pulls, route.n, route.a, route.d = last.pulls, last.n, last.a, last.d
	self:Changed("route")
	return true
end

-- A new, empty route of yours for a dungeon (picked at once).
function M:NewRoute(key, name)
	if not (type(key) == "string" and key:match("^[%w_]+$")) then return nil end
	if self:UserRouteCount() >= MAX_ROUTES then return nil, L["you have too many routes; delete some first"] end
	local store = self:Store()
	local id = store.nextId
	store.nextId = id + 1
	name = CleanText(name, MAX_NAME) or (L["My %s route"]):format(self:DungeonName(key))
	local route = { key = key, name = name, pulls = {}, created = time and time() or 0, id = id }
	store.routes[id] = route
	self:SetActiveRoute(key, route)
	return route
end

-- The pull that holds a pack, or nil.
function M:PullOfPack(route, packId)
	for index, pull in ipairs(type(route) == "table" and route.pulls or {}) do
		for _, id in ipairs(pull.p or {}) do
			if id == packId then return index end
		end
	end
end

-- A click on a pack in the editor: a pack in the route comes out of its
-- pull (an empty pull goes); another one becomes a new pull at the end,
-- or joins pull `into` (Shift-click with a pull picked). Returns
-- "removed", "added" or "joined", or false.
function M:TogglePack(id, packId, into)
	packId = tonumber(packId)
	if not packId then return false end
	local _, action = self:EditRoute(id, function(route)
		local at = self:PullOfPack(route, packId)
		if at then
			local pull = route.pulls[at]
			for index = #pull.p, 1, -1 do
				if pull.p[index] == packId then table.remove(pull.p, index) end
			end
			if #pull.p == 0 then table.remove(route.pulls, at) end
			return true, "removed"
		end
		local target = into and route.pulls[into]
		if target then
			if #target.p >= MAX_PACKS_PER_PULL then return false end
			target.p[#target.p + 1] = packId
			return true, "joined"
		end
		if #route.pulls >= MAX_PULLS then return false end
		route.pulls[#route.pulls + 1] = { p = { packId } }
		return true, "added"
	end)
	return action or false
end

-- Moves pull `from` to place `to` (drag and drop, Move up and down).
function M:MovePull(id, from, to)
	from, to = tonumber(from), tonumber(to)
	return (self:EditRoute(id, function(route)
		if not (from and to and route.pulls[from]) then return false end
		to = math.max(1, math.min(#route.pulls, to))
		if from == to then return false end
		local pull = table.remove(route.pulls, from)
		table.insert(route.pulls, to, pull)
		return true
	end))
end

function M:DeletePull(id, index)
	return (self:EditRoute(id, function(route)
		if not route.pulls[index] then return false end
		table.remove(route.pulls, index)
		return true
	end))
end

-- Pull `index` joins the pull before it (one pull of both packs).
function M:MergePull(id, index)
	return (self:EditRoute(id, function(route)
		local pull, before = route.pulls[index], route.pulls[(index or 0) - 1]
		if not (pull and before) or #before.p + #pull.p > MAX_PACKS_PER_PULL then return false end
		for _, packId in ipairs(pull.p) do before.p[#before.p + 1] = packId end
		before.l = before.l or pull.l
		before.c = before.c or pull.c
		table.remove(route.pulls, index)
		return true
	end))
end

-- Notes, arrows and free-hand lines (world yards on a floor).
local function AddTo(route, field, entry, limit)
	if not entry then return false end
	route[field] = route[field] or {}
	if #route[field] >= limit then
		if #route[field] == 0 then route[field] = nil end
		return false
	end
	route[field][#route[field] + 1] = entry
	return true
end

function M:AddNote(id, floor, x, y, text, color)
	return (self:EditRoute(id, function(route)
		return AddTo(route, "n", CleanNote({ x = x, y = y, f = floor, t = text, c = color }), MAX_NOTES)
	end))
end

-- A note's new text; an empty text deletes the note.
function M:SetNoteText(id, index, text)
	return (self:EditRoute(id, function(route)
		local note = route.n and route.n[index]
		if not note then return false end
		text = CleanText(text)
		if not text then
			table.remove(route.n, index)
			if #route.n == 0 then route.n = nil end
			return true
		end
		if note.t == text then return false end
		note.t = text
		return true
	end))
end

function M:AddArrow(id, floor, x1, y1, x2, y2, color)
	return (self:EditRoute(id, function(route)
		return AddTo(route, "a", CleanArrow({ x1 = x1, y1 = y1, x2 = x2, y2 = y2, f = floor, c = color }), MAX_ARROWS)
	end))
end

-- points: { x, y, x, y, ... } in world yards (thinned to MAX_STROKE_POINTS).
function M:AddStroke(id, floor, points, color)
	if type(points) ~= "table" then return false end
	local count = math.floor(#points / 2)
	local flat = points
	if count > MAX_STROKE_POINTS then
		flat = {}
		for step = 0, MAX_STROKE_POINTS - 1 do
			local index = math.floor(step * (count - 1) / (MAX_STROKE_POINTS - 1) + 0.5) * 2 + 1
			flat[#flat + 1], flat[#flat + 2] = points[index], points[index + 1]
		end
	end
	return (self:EditRoute(id, function(route)
		return AddTo(route, "d", CleanStroke({ f = floor, c = color, p = flat }), MAX_STROKES)
	end))
end

local function SegmentDistance(px, py, x1, y1, x2, y2)
	local dx, dy = x2 - x1, y2 - y1
	local length = dx * dx + dy * dy
	local t = length > 0 and math.max(0, math.min(1, ((px - x1) * dx + (py - y1) * dy) / length)) or 0
	local cx, cy = x1 + t * dx, y1 + t * dy
	return math.sqrt((px - cx) ^ 2 + (py - cy) ^ 2)
end

-- The note, arrow or line on `floor` nearest to x, y within `radius`
-- yards: field ("n", "a" or "d"), index, distance.
function M:DrawingNear(route, floor, x, y, radius)
	if type(route) ~= "table" or not (x and y) then return nil end
	floor = FloorOf(floor)
	local bestField, bestIndex, best = nil, nil, radius or 10
	for index, note in ipairs(route.n or {}) do
		local distance = math.sqrt((note.x - x) ^ 2 + (note.y - y) ^ 2)
		if note.f == floor and distance <= best then bestField, bestIndex, best = "n", index, distance end
	end
	for index, arrow in ipairs(route.a or {}) do
		local distance = SegmentDistance(x, y, arrow.x1, arrow.y1, arrow.x2, arrow.y2)
		if arrow.f == floor and distance <= best then bestField, bestIndex, best = "a", index, distance end
	end
	for index, stroke in ipairs(route.d or {}) do
		if stroke.f == floor then
			local p = stroke.p
			for i = 1, #p - 3, 2 do
				local distance = SegmentDistance(x, y, p[i], p[i + 1], p[i + 2], p[i + 3])
				if distance <= best then bestField, bestIndex, best = "d", index, distance end
			end
		end
	end
	return bestField, bestIndex, bestField and best or nil
end

-- Erase the nearest note, arrow or line (the editor's eraser).
function M:EraseNear(id, floor, x, y, radius)
	return (self:EditRoute(id, function(route)
		local field, index = self:DrawingNear(route, floor, x, y, radius)
		if not field then return false end
		table.remove(route[field], index)
		if #route[field] == 0 then route[field] = nil end
		return true
	end))
end

-- Every note, arrow and line on one floor (or on every floor) goes.
function M:ClearDrawings(id, floor)
	return (self:EditRoute(id, function(route)
		local changed = false
		for _, field in ipairs({ "n", "a", "d" }) do
			local list = route[field]
			for index = #(list or {}), 1, -1 do
				if not floor or list[index].f == floor then
					table.remove(list, index)
					changed = true
				end
			end
			if list and #list == 0 then route[field] = nil end
		end
		return changed
	end))
end

-- A pull's packs, its center (world yards), its mob count and whether it
-- holds a boss or an elite.
function M:PullInfo(key, pull)
	local info = { packs = {}, count = 0, x = 0, y = 0 }
	local weight = 0
	for _, id in ipairs(type(pull) == "table" and pull.p or {}) do
		local pack = self:Pack(key, id)
		if pack then
			info.packs[#info.packs + 1] = pack
			info.count = info.count + pack.count
			info.x, info.y = info.x + pack.x * pack.count, info.y + pack.y * pack.count
			weight = weight + pack.count
			if pack.boss then info.boss = info.boss or pack.boss end
			if pack.elite then info.elite = true end
			if pack.path then info.patrol = true end
		end
	end
	if weight == 0 then return info end
	info.x, info.y = info.x / weight, info.y / weight
	info.found = true
	return info
end

-- The text of a pull in lists: its label, else what it holds.
function M:PullText(key, pull)
	if type(pull) ~= "table" then return "" end
	if pull.l then return pull.l end
	local info = self:PullInfo(key, pull)
	if info.boss then return (L["Boss: %s"]):format(self:BossName(key, info.boss)) end
	local first = info.packs[1] and info.packs[1].members[1]
	if not first then return L["Pack not in this data"] end
	if info.count <= 1 then return first.name end
	return (L["%d mobs (%s)"]):format(info.count, first.name)
end

