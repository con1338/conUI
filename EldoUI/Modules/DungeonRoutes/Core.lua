-- The dungeon you are in (no position: the instance and its name)
---------------------------------------------------------------------------
local function Fold(text)
	return tostring(text or ""):lower():gsub("[^%w]", "")
end

-- The route key of the dungeon you stand in, or nil.
function M:CurrentDungeon()
	local DM = E.DungeonMaps
	local mapKey = DM and DM:CurrentDungeon()
	if not mapKey then return nil end
	local wings = {}
	for _, entry in ipairs(self:Dungeons()) do
		if self:MapKey(entry.key) == mapKey then wings[#wings + 1] = entry end
	end
	if #wings <= 1 then return wings[1] and wings[1].key or nil end
	-- Several wings on one map: the zone texts may name the wing.
	local texts = {}
	for _, fn in ipairs({ GetSubZoneText, GetRealZoneText, GetZoneText, GetMinimapZoneText }) do
		local ok, text = pcall(fn)
		if ok and type(text) == "string" and not Secret(text) and text ~= "" then texts[#texts + 1] = Fold(text) end
	end
	if GetInstanceInfo then
		local name = GetInstanceInfo()
		if type(name) == "string" and not Secret(name) then texts[#texts + 1] = Fold(name) end
	end
	-- Each wing's own part of its name ("library" of "Scarlet Monastery:
	-- Library"): the wings share the rest, so the rest decides nothing.
	local folded = {}
	for index, entry in ipairs(wings) do folded[index] = Fold(entry.name) end
	local common = folded[1]
	for index = 2, #folded do
		local other, length = folded[index], 0
		while length < #common and common:sub(length + 1, length + 1) == other:sub(length + 1, length + 1) do length = length + 1 end
		common = common:sub(1, length)
	end
	for index, entry in ipairs(wings) do
		local own = folded[index]:sub(#common + 1)
		for _, text in ipairs(texts) do
			if text == folded[index] or (#own >= 3 and text:find(own, 1, true)) then return entry.key end
		end
	end
	local last = self:Store().lastWing and self:Store().lastWing[mapKey]
	for _, entry in ipairs(wings) do if entry.key == last then return last end end
	return wings[1].key
end

function M:RememberWing(key)
	local mapKey = self:MapKey(key)
	if not mapKey then return end
	local store = self:Store()
	store.lastWing = type(store.lastWing) == "table" and store.lastWing or {}
	store.lastWing[mapKey] = key
end

