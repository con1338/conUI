-- EldoUI Dungeon Routes (phase 1): the packs, patrols and bosses of the
-- Classic dungeons on the dungeon map, with routes of numbered pulls that
-- you can keep and share.
--
-- Files:
--   Core.lua     the module, its settings, the data, the route model, saved
--                routes, the !EUR1! share kind and /eui routes
--   Overlay.lua  the map overlay: pack and boss markers, patrol paths and the
--                route line with pull numbers, drawn through E.DungeonMaps on
--                the browser's map and (optional) the Loot Guide's dungeon map
--   Browser.lua  the "Dungeons" window: dungeon list, floors, route picker,
--                pull list, your routes; opens the dungeon you are in
--   Editor.lua   the route editor in that window: click packs to add or
--                take out pulls, drag pulls to reorder them, notes, arrows
--                and free-hand lines on the map, undo
--   WorldMap.lua the dungeon view on the world map: inside a dungeon, M (and
--                every map button) shows the dungeon's floor with the packs
--                and the route instead of Blizzard's empty instance map
--   Group.lua    send a route to your group with one click, and the "From
--                your group" list of routes others sent (opt-in)
--   Card.lua     the route card: the next pulls of the route in a small
--                movable card inside a dungeon (off by default)
--   Packs.lua    hand-placed packs for dungeons the Classic data lacks
--                (M:RegisterPacks), for WoW: Forever's own dungeons
--
-- Data: EldoUI_LootData/Routes.lua (GPL-3.0-or-later, generated by
-- tools/lootdata/routes.py from CMaNGOS classic-db). EldoUI itself holds no
-- copy: the packs are read at runtime from the load-on-demand data folder,
-- the way the Loot Guide reads its loot tables (LG:LoadData). Record format:
--   LD.routePacks[key]   = { "id|x,y,z|npc*count,...|flags|x,y;...", ... }
--       id: the pack's lowest spawn guid (stable between data versions);
--       x, y, z: world yards; flags: b<n> boss n of the kill order, r rare
--       boss, p patrol (the path follows: up to 8 points)
--   LD.routeShipped[key] = "pack,pack,..." indices into routePacks[key]
--   LD.routeMobs[npc]    = "name|minLevel|maxLevel|rank" (pack creatures
--       that Creatures.lua leaves out; the rest are in LD.mobs)
--
-- Route model (shipped, saved and shared alike):
--   route = { key = "deadmines", name = "My route", pulls = {
--       { p = { packId, ... }, l = "label" or nil, c = "color key" or nil }, ... },
--     n = { { x, y, f, t, c }, ... },          notes: world yards, floor, text, color
--     a = { { x1, y1, x2, y2, f, c }, ... },   arrows
--     d = { { f, c, p = { x, y, x, y, ... } }, ... } }  free-hand lines
--   Color keys: E.DungeonRoutes.COLORS (accent, red, orange, yellow, green,
--   teal, blue, purple). The shipped route of each dungeon is built from the
--   data: a full clear in boss-to-boss order, bosses labeled.
--   Your routes are account-wide: E.global.DungeonRoutes.routes[id].
--
-- Rules: planning and display only. Nothing here pulls, targets or marks
-- anything. A route reaches another player only as a string you copy, or
-- when you click "Send to group" (addon messages, never while the game holds
-- them back); received routes wait in a list until you keep one, and
-- nothing is ever answered. The world-map view shows your own dot only when
-- the game itself gives your map position; nothing works one out.
