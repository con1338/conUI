function M:DescribeShareData(data)
	local clean, err = self:SanitizeRoute(data)
	if not clean then return { (L["This route can't be used: %s."]):format(tostring(err)) } end
	local lines = {}
	lines[#lines + 1] = (L["%s: \"%s\", %d pulls."]):format(self:DungeonName(clean.key), clean.name, #clean.pulls)
	local labelled = 0
	for _, pull in ipairs(clean.pulls) do if pull.l then labelled = labelled + 1 end end
	if labelled > 0 then lines[#lines + 1] = (L["%d pulls have a label."]):format(labelled) end
	local drawings = self:DrawingCount(clean)
	if drawings > 0 then lines[#lines + 1] = (L["%d notes, arrows and lines on the map."]):format(drawings) end
	if self:Data(true) and not self:DungeonInfo(clean.key) then
		lines[#lines + 1] = L["Your dungeon data doesn't know this dungeon; the route is kept and shows once it does."]
	end
	lines[#lines + 1] = L["It is added to your routes. Nothing you have is changed."]
	return lines
end

