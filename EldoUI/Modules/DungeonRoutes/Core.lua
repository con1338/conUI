local status = "pending"   -- pending | loaded | missing | disabled | old | failed
local packCache = {}       -- key -> decoded packs
local shippedCache = {}    -- key -> shipped route
-- Hand-placed packs of dungeons the Classic data lacks (Packs.lua,
-- M:RegisterPacks): key -> { name, map, min, max, packs = { record, ... },
-- shipped = "1,2,...", mobs = { [npc] = "name|min|max|rank" }, bosses = { name, ... } }
local extra = {}
M.extraPacks = extra

-- Forget what was decoded for one dungeon (new hand-placed packs).
function M:ForgetPacks(key)
	packCache[key] = nil
	shippedCache[key] = nil
	if E.DungeonMaps then E.DungeonMaps:Reset() end
end

local function Adopt()
	local data = rawget(_G, DATA_ADDON)
	if type(data) ~= "table" then return nil end
	if type(data.routePacks) ~= "table" then
		status = "old"
		return nil
	end
	if status ~= "loaded" then
		status = "loaded"
		wipe(packCache)
		wipe(shippedCache)
		-- The schematic view's box comes from the packs: work it out again.
		if E.DungeonMaps then E.DungeonMaps:Reset() end
	end
	return data
end

-- The data table, loading the folder first when we may. The Loot Guide's
-- loader is used when that module is on, so both share one load.
function M:Data(noLoad)
	local data = Adopt()
	if data or noLoad then return data end
	if status == "missing" or status == "disabled" or status == "old" then return nil end
	if InCombatLockdown() then
		self.loadAfterCombat = true
		return nil
	end
	local LG = E:GetModule("LootGuide")
	if LG and LG.active and LG.LoadData then
		pcall(LG.LoadData, LG)
		data = Adopt()
		if data then return data end
	end
	if not (C_AddOns and C_AddOns.GetAddOnInfo) then
		status = "missing"
		return nil
	end
	local name, _, _, _, reason = C_AddOns.GetAddOnInfo(DATA_ADDON)
	if not name then
		status = "missing"
		return nil
	end
	if reason == "DISABLED" or reason == "DEP_DISABLED" then
		status = "disabled"
		return nil
	end
	local loaded = C_AddOns.LoadAddOn(DATA_ADDON)
	data = Adopt()
	if not data and not loaded then status = "failed" end
	return data
end

function M:DataStatus()
	self:Data(true)
	return status
end

-- What the empty state says when there is no data.
function M:DataProblem()
	local state = self:DataStatus()
	if state == "loaded" then return nil end
	if state == "old" then
		return L["Dungeon data is too old"], L["Your EldoUI_LootData has no dungeon packs yet. Update it together with EldoUI."]
	elseif state == "disabled" then
		return L["Dungeon data is switched off"], L["Turn on EldoUI Loot Data in the addon list, then reload."]
	elseif state == "missing" then
		return L["Dungeon data is not installed"], L["The packs come from the EldoUI_LootData folder that ships next to EldoUI. Install it beside EldoUI in Interface\\AddOns."]
	elseif state == "failed" then
		return L["Dungeon data could not load"], L["The game refused to load EldoUI_LootData. Check the addon list."]
	end
	return L["Dungeon data loads out of combat"], L["Open the window again when combat ends."]
end

-- Dungeon list: { { key, name, map, min, max }, ... } in the data's order.
function M:Dungeons()
	local data = self:Data(true)
	local list = {}
	local seen = {}
	if data then
		local order = type(data.instanceOrder) == "table" and data.instanceOrder or {}
		local function Add(key)
			if seen[key] or type(data.routePacks[key]) ~= "table" then return end
			seen[key] = true
			local info = type(data.instances) == "table" and data.instances[key] or {}
			if type(info) ~= "table" then info = {} end
			list[#list + 1] = { key = key, name = tostring(info.name or key), map = tonumber(info.map),
				min = tonumber(info.min), max = tonumber(info.max) }
		end
		for _, key in ipairs(order) do Add(key) end
		local rest = {}
		for key in pairs(data.routePacks) do if not seen[key] then rest[#rest + 1] = key end end
		table.sort(rest)
		for _, key in ipairs(rest) do Add(key) end
	end
	-- Hand-placed dungeons last, by name.
	local own = {}
	for key, def in pairs(extra) do
		if not seen[key] then own[#own + 1] = { key = key, name = tostring(def.name or key), map = tonumber(def.map),
			min = tonumber(def.min), max = tonumber(def.max), handPlaced = true } end
	end
	table.sort(own, function(a, b) return a.name < b.name end)
	for _, entry in ipairs(own) do list[#list + 1] = entry end
	return list
end

function M:DungeonInfo(key)
	for _, entry in ipairs(self:Dungeons()) do
		if entry.key == key then return entry end
	end
end

function M:DungeonName(key)
	local info = self:DungeonInfo(key)
	return info and info.name or tostring(key or "?")
end

-- The E.DungeonMaps key for a dungeon (wings share their map's key).
function M:MapKey(key)
	local DM = E.DungeonMaps
	if not DM then return nil end
	local mapKey = DM:KeyFor(key)
	if mapKey then return mapKey end
	local info = self:DungeonInfo(key)
	return info and info.map and DM:KeyForMap(info.map) or nil
end

