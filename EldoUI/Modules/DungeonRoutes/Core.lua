-- { name, min, max, rank } for an npc id, from LD.mobs or LD.routeMobs.
function M:Mob(npc)
	local data = self:Data(true) or {}
	local record = (type(data.mobs) == "table" and data.mobs[npc]) or (type(data.routeMobs) == "table" and data.routeMobs[npc])
	if type(record) ~= "string" then
		for _, def in pairs(extra) do
			if type(def.mobs) == "table" and type(def.mobs[npc]) == "string" then record = def.mobs[npc] break end
		end
	end
	if type(record) ~= "string" then return nil end
	local name, min, max, rank = record:match("^([^|]*)|(%d*)|(%d*)|(%d*)")
	local L10n = type(data.L) == "table" and type(data.L.mobs) == "table" and data.L.mobs[npc]
	return { name = (type(L10n) == "string" and L10n ~= "") and L10n or name, min = tonumber(min), max = tonumber(max), rank = tonumber(rank) or 0 }
end

local function DecodePack(record, index)
	local id, x, y, z, members, flags, path = record:match("^(%d+)|(%-?%d+),(%-?%d+),(%-?%d+)|([^|]*)|?([^|]*)|?(.*)$")
	if not id then return nil end
	local pack = { index = index, id = tonumber(id), x = tonumber(x), y = tonumber(y), z = tonumber(z), members = {}, count = 0 }
	for npc, count in members:gmatch("(%d+)%*?(%d*)") do
		count = tonumber(count) or 1
		pack.members[#pack.members + 1] = { npc = tonumber(npc), count = count }
		pack.count = pack.count + count
	end
	pack.boss = tonumber(flags:match("b(%d+)"))
	pack.rare = flags:find("r", 1, true) ~= nil
	if flags:find("p", 1, true) and path ~= "" then
		pack.path = {}
		for px, py in path:gmatch("(%-?%d+),(%-?%d+)") do pack.path[#pack.path + 1] = { x = tonumber(px), y = tonumber(py) } end
	end
	return pack
end

-- Ranks: 1 elite, 2 rare elite, 3 boss, 4 rare.
local function FillRanks(self, pack)
	local elite, best = false, 0
	for _, member in ipairs(pack.members) do
		local mob = self:Mob(member.npc)
		local rank = mob and mob.rank or 0
		member.name = mob and mob.name or ("#" .. member.npc)
		member.rank = rank
		member.level = mob and mob.max
		if rank == 1 or rank == 2 or rank == 3 then elite = true end
		if rank > best then best = rank end
	end
	pack.elite = elite
	pack.rank = best
end

-- Decoded packs of a dungeon (cached): { { index, id, x, y, z, count,
-- members = { { npc, count, name, rank, level } }, elite, boss, rare, path } }.
function M:Packs(key)
	if not key then return {} end
	local cached = packCache[key]
	if cached then return cached end
	local data = self:Data(true)
	local raw = data and data.routePacks[key]
	if type(raw) ~= "table" then raw = extra[key] and extra[key].packs end
	if type(raw) ~= "table" then return {} end
	local packs, byID = {}, {}
	for index, record in ipairs(raw) do
		local pack = type(record) == "string" and DecodePack(record, index)
		if pack then
			FillRanks(self, pack)
			packs[#packs + 1] = pack
			byID[pack.id] = pack
		end
	end
	packs.byID = byID
	packCache[key] = packs
	return packs
end

function M:Pack(key, id)
	return self:Packs(key).byID[tonumber(id) or -1]
end

-- Boss names of a dungeon in kill order (index -> name).
function M:BossName(key, index)
	local data = self:Data(true)
	local info = data and type(data.instances) == "table" and data.instances[key]
	local boss = type(info) == "table" and type(info.bosses) == "table" and info.bosses[index]
	local mob = type(boss) == "table" and boss.npc and self:Mob(boss.npc)
	if mob then return mob.name end
	local own = extra[key] and type(extra[key].bosses) == "table" and extra[key].bosses[index]
	if type(own) == "string" then return own end
	for _, pack in ipairs(self:Packs(key)) do
		if pack.boss == index then
			for _, member in ipairs(pack.members) do
				if member.rank == 3 or member.rank == 1 then return member.name end
			end
		end
	end
	return (L["Boss %d"]):format(index)
end

