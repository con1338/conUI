function M:FindDungeon(word)
	word = Fold(word)
	if word == "" then return nil end
	local data = self:Data(true)
	for _, entry in ipairs(self:Dungeons()) do
		if Fold(entry.key) == word or Fold(entry.name) == word then return entry.key end
		local info = data and data.instances and data.instances[entry.key]
		for _, alias in ipairs(type(info) == "table" and type(info.aliases) == "table" and info.aliases or {}) do
			if Fold(alias) == word then return entry.key end
		end
	end
	for _, entry in ipairs(self:Dungeons()) do
		if Fold(entry.name):find(word, 1, true) then return entry.key end
	end
end

function M:Command(arg)
	arg = strtrim(arg or "")
	local word = arg:lower()
	if word == "import" then
		self:ShowImport()
		return
	end
	if not self.OpenBrowser then return end
	if arg == "" then
		self:OpenBrowser()
		return
	end
	self:Data()
	local key = self:FindDungeon(arg)
	if not key then
		E:Print((L["Dungeon Routes: no dungeon called \"%s\"."]):format(arg))
		return
	end
	self:OpenBrowser(key)
end

