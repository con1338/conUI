-- The other files hook in here: M:Hook(name, fn) with name "enable",
-- "disable", "zone" (zoning, entering the world), "combat" (combat starts),
-- "combatEnd", "profile" and "changed" (fn(what), after M:Changed).
local hooks = {}
function M:Hook(name, fn)
	hooks[name] = hooks[name] or {}
	table.insert(hooks[name], fn)
end

local function RunHooks(name, ...)
	for _, fn in ipairs(hooks[name] or {}) do
		local ok, err = pcall(fn, ...)
		if not ok then geterrorhandler()(err) end
	end
end
M.RunHooks = RunHooks

local events = CreateFrame("Frame")
events:SetScript("OnEvent", function(_, event)
	if not M.active then return end
	if event == "PLAYER_REGEN_ENABLED" then
		if M.loadAfterCombat then
			M.loadAfterCombat = nil
			if M:Data() then M:Changed("data") end
		end
		if M.openAfterCombat then
			local key = M.openAfterCombat
			M.openAfterCombat = nil
			M:OpenBrowser(key ~= true and key or nil)
		end
		RunHooks("combatEnd")
	elseif event == "PLAYER_REGEN_DISABLED" then
		RunHooks("combat")
	else
		if M.OnZoneChanged then M:OnZoneChanged() end
		RunHooks("zone", event)
	end
end)

function M:OnInitialize()
	E:RegisterGlobal("DungeonRoutes", { routes = {}, nextId = 1, pick = {} },
		{ title = "Dungeon routes", desc = "Your own dungeon routes and the route picked per dungeon." })
	local LG = E:GetModule("LootGuide")
	if LG and LG.On then
		LG:On("dungeonroutes", function(changed)
			if changed.data and Adopt() then M:Changed("data") end
		end)
	end
end

function M:OnEnable()
	events:RegisterEvent("PLAYER_REGEN_ENABLED")
	events:RegisterEvent("PLAYER_REGEN_DISABLED")
	events:RegisterEvent("ZONE_CHANGED_NEW_AREA")
	events:RegisterEvent("ZONE_CHANGED_INDOORS")
	events:RegisterEvent("PLAYER_ENTERING_WORLD")
	if self.EnableOverlay then self:EnableOverlay() end
	RunHooks("enable")
end

function M:OnDisable()
	events:UnregisterAllEvents()
	if self.DisableOverlay then self:DisableOverlay() end
	if self.CloseBrowser then self:CloseBrowser() end
	RunHooks("disable")
end

function M:OnProfileChanged()
	if not self.active then return end
	self:Changed("settings")
	if self.RestyleBrowser then self:RestyleBrowser() end
	RunHooks("profile")
end

-- Test hook: forget decoded data (a new LootData table).
function M:ResetData()
	status = "pending"
	wipe(packCache)
	wipe(shippedCache)
end

