function M:Store()
	local store = E:GetGlobal("DungeonRoutes")
	if type(store) ~= "table" then
		self.memoryStore = self.memoryStore or { routes = {}, nextId = 1, pick = {} }
		store = self.memoryStore
	end
	if type(store.routes) ~= "table" then store.routes = {} end
	if type(store.pick) ~= "table" then store.pick = {} end
	store.nextId = tonumber(store.nextId) or 1
	return store
end

-- The shipped route of a dungeon: the data's boss-to-boss full clear.
function M:ShippedRoute(key)
	if shippedCache[key] then return shippedCache[key] end
	local data = self:Data(true)
	local raw = data and type(data.routeShipped) == "table" and data.routeShipped[key]
	if type(raw) ~= "string" then raw = extra[key] and extra[key].shipped end
	if type(raw) ~= "string" then return nil end
	local packs = self:Packs(key)
	local route = { key = key, name = L["Boss to boss (full clear)"], shipped = true, pulls = {} }
	for index in raw:gmatch("(%d+)") do
		local pack = packs[tonumber(index)]
		if pack then
			local pull = { p = { pack.id } }
			if pack.boss then
				pull.l = (L["Boss: %s"]):format(self:BossName(key, pack.boss))
				pull.c = "red"
			elseif pack.path then
				pull.l = L["Patrol"]
				pull.c = "yellow"
			end
			route.pulls[#route.pulls + 1] = pull
		end
	end
	shippedCache[key] = route
	return route
end

-- Every route of a dungeon: the shipped one first, then yours by name.
function M:Routes(key)
	local list = {}
	local shipped = self:ShippedRoute(key)
	if shipped then list[1] = shipped end
	local mine = {}
	for id, route in pairs(self:Store().routes) do
		if type(route) == "table" and route.key == key then
			route.id = id
			mine[#mine + 1] = route
		end
	end
	table.sort(mine, function(a, b)
		local na, nb = tostring(a.name or ""):lower(), tostring(b.name or ""):lower()
		if na ~= nb then return na < nb end
		return a.id < b.id
	end)
	for _, route in ipairs(mine) do list[#list + 1] = route end
	return list
end

function M:AllUserRoutes()
	local list = {}
	for id, route in pairs(self:Store().routes) do
		if type(route) == "table" then
			route.id = id
			list[#list + 1] = route
		end
	end
	table.sort(list, function(a, b)
		local da, db = self:DungeonName(a.key), self:DungeonName(b.key)
		if da ~= db then return da < db end
		local na, nb = tostring(a.name or ""):lower(), tostring(b.name or ""):lower()
		if na ~= nb then return na < nb end
		return a.id < b.id
	end)
	return list
end

function M:GetRoute(id)
	local route = self:Store().routes[tonumber(id) or -1]
	if type(route) == "table" then
		route.id = tonumber(id)
		return route
	end
end

-- The route picked for a dungeon (yours when you picked one, else shipped).
function M:ActiveRoute(key)
	local pick = self:Store().pick[key]
	if pick and pick ~= "shipped" then
		local route = self:GetRoute(pick)
		if route and route.key == key then return route end
	end
	return self:ShippedRoute(key)
end

function M:SetActiveRoute(key, route)
	if not key then return end
	local store = self:Store()
	store.pick[key] = (type(route) == "table" and route.id) or (tonumber(route)) or "shipped"
	self:Changed("route")
end

-- Clean parts of a route (shared by the share string, the editor and
-- plugins): whole world yards, a floor of 1 to MAX_FLOOR, short texts
-- without escape codes, known colors.
local function Coord(value)
	value = tonumber(value)
	if not value or value ~= value or math.abs(value) > 100000 then return nil end
	return math.floor(value + 0.5)
end

local function FloorOf(value)
	value = tonumber(value)
	if value and value >= 1 and value <= MAX_FLOOR and value == math.floor(value) then return value end
	return 1
end

local function CleanText(text, limit)
	if type(text) ~= "string" then return nil end
	text = strtrim(text):gsub("|", "/")
	if text == "" then return nil end
	return text:sub(1, limit or MAX_LABEL)
end
M.CleanText = CleanText

local function CleanColor(key)
	return type(key) == "string" and key ~= "accent" and colorByKey[key] and key or nil
end

local function CleanNote(note)
	if type(note) ~= "table" then return nil end
	local x, y, text = Coord(note.x), Coord(note.y), CleanText(note.t)
	if not (x and y and text) then return nil end
	return { x = x, y = y, f = FloorOf(note.f), t = text, c = CleanColor(note.c) }
end

local function CleanArrow(arrow)
	if type(arrow) ~= "table" then return nil end
	local x1, y1, x2, y2 = Coord(arrow.x1), Coord(arrow.y1), Coord(arrow.x2), Coord(arrow.y2)
	if not (x1 and y1 and x2 and y2) or (x1 == x2 and y1 == y2) then return nil end
	return { x1 = x1, y1 = y1, x2 = x2, y2 = y2, f = FloorOf(arrow.f), c = CleanColor(arrow.c) }
end

local function CleanStroke(stroke)
	if type(stroke) ~= "table" or type(stroke.p) ~= "table" then return nil end
	local points = {}
	for index = 1, math.min(#stroke.p, MAX_STROKE_POINTS * 2) - 1, 2 do
		local x, y = Coord(stroke.p[index]), Coord(stroke.p[index + 1])
		if not (x and y) then return nil end
		points[#points + 1], points[#points + 2] = x, y
	end
	if #points < 4 then return nil end
	return { f = FloorOf(stroke.f), c = CleanColor(stroke.c), p = points }
end
M.CleanNote, M.CleanArrow, M.CleanStroke = CleanNote, CleanArrow, CleanStroke

local function CleanList(list, clean, limit)
	local out = {}
	if type(list) ~= "table" then return out end
	for _, entry in ipairs(list) do
		if #out >= limit then break end
		local copy = clean(entry)
		if copy then out[#out + 1] = copy end
	end
	return out
end

-- How many notes, arrows and lines a route has.
function M:DrawingCount(route)
	if type(route) ~= "table" then return 0 end
	return #(route.n or {}) + #(route.a or {}) + #(route.d or {})
end

-- A clean copy of a route table from anywhere (a share string, a plugin):
-- known dungeon, at most MAX_PULLS pulls, pack ids as numbers, short
-- labels and known colors, capped notes, arrows and lines. Returns the
-- copy, or nil and a reason.
function M:SanitizeRoute(route)
	if type(route) ~= "table" then return nil, L["not a route"] end
	local key = type(route.key) == "string" and route.key or nil
	if not key or #key > 32 or not key:match("^[%w_]+$") then return nil, L["no dungeon in the route"] end
	local clean = { key = key, pulls = {} }
	local name = type(route.name) == "string" and strtrim(route.name) or ""
	clean.name = name ~= "" and name:gsub("|", "/"):sub(1, MAX_NAME) or L["Imported route"]
	for _, pull in ipairs(type(route.pulls) == "table" and route.pulls or {}) do
		if #clean.pulls >= MAX_PULLS then break end
		if type(pull) == "table" and type(pull.p) == "table" then
			local ids = {}
			for _, id in ipairs(pull.p) do
				id = tonumber(id)
				if id and id > 0 and id == math.floor(id) and #ids < MAX_PACKS_PER_PULL then ids[#ids + 1] = id end
			end
			if #ids > 0 then
				local entry = { p = ids }
				entry.l = CleanText(pull.l)
				if type(pull.c) == "string" and colorByKey[pull.c] then entry.c = pull.c end
				clean.pulls[#clean.pulls + 1] = entry
			end
		end
	end
	local notes, arrows, strokes = CleanList(route.n, CleanNote, MAX_NOTES), CleanList(route.a, CleanArrow, MAX_ARROWS), CleanList(route.d, CleanStroke, MAX_STROKES)
	if #notes > 0 then clean.n = notes end
	if #arrows > 0 then clean.a = arrows end
	if #strokes > 0 then clean.d = strokes end
	if #clean.pulls == 0 and self:DrawingCount(clean) == 0 then return nil, L["the route has no pulls"] end
	return clean
end

function M:UserRouteCount()
	local count = 0
	for _ in pairs(self:Store().routes) do count = count + 1 end
	return count
end

-- Keeps a route as one of yours (a copy); returns it.
function M:SaveRoute(route, name)
	local clean, err = self:SanitizeRoute(route)
	if not clean then return nil, err end
	if self:UserRouteCount() >= MAX_ROUTES then return nil, L["you have too many routes; delete some first"] end
	if name and strtrim(name) ~= "" then clean.name = strtrim(name):sub(1, MAX_NAME) end
	local store = self:Store()
	local id = store.nextId
	store.nextId = id + 1
	clean.created = time and time() or 0
	store.routes[id] = clean
	clean.id = id
	self:Changed("routes")
	return clean
end

function M:CopyRoute(route)
	if type(route) ~= "table" then return nil end
	local name = (L["%s (copy)"]):format(route.name or L["Route"])
	if route.shipped then name = (L["My %s route"]):format(self:DungeonName(route.key)) end
	local copy = self:SaveRoute(route, name)
	if copy then self:SetActiveRoute(copy.key, copy) end
	return copy
end

